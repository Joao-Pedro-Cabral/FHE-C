static const uint8_t rcon[10] = {0x01, 0x02, 0x04, 0x08, 0x10,
                                 0x20, 0x40, 0x80, 0x1b, 0x36};

/*
 * AES-128 key expansion.
 *
 * key       : 16-byte AES-128 key
 * round_keys: 11 * 16 bytes
 *
 * round_keys[ 0..15]   = round 0 key
 * round_keys[16..31]   = round 1 key
 * ...
 * round_keys[160..175] = round 10 key
 */
void aes128_key_expand(const uint8_t key[16]) {
  uint8_t round_keys[11][16];
  /* Round 0 */
  for (int i = 0; i < 16; i++) round_keys[0][i] = key[i];

  for (int round = 1; round <= 10; round++) {
    const uint8_t *prev = round_keys[round - 1];
    uint8_t *rk = round_keys[round];

    /* First word = SubWord(RotWord(previous last word)) ^ Rcon */
    rk[0] = prev[0] ^ sbox[prev[13]] ^ rcon[round - 1];
    rk[1] = prev[1] ^ sbox[prev[14]];
    rk[2] = prev[2] ^ sbox[prev[15]];
    rk[3] = prev[3] ^ sbox[prev[12]];

    /* Remaining words */
    for (int i = 4; i < 16; i++) rk[i] = prev[i] ^ rk[i - 4];
  }

  for (uint32_t i = 0; i < 11; i++) {
    for (uint32_t j = 0; j < 16; j++) {
      printf("round[%d][%d]: 0x%02x\n", i, j, round_keys[i][j]);
    }
  }
}

int main() {
  bool good = true;
  poly_t e1, e2;
  uint32_t n = 16;
  poly_new(&e1, n);
  poly_new(&e2, n);

  printf("---------- TEST CBD ----------\n");

  poly_cbd24_sampler(e1, n);
  test_cbd(e2, n);

  for (uint32_t i = 0; i < n; i++) {
    if (e1[i] != e2[i]) {
      good = false;
      printf("e1[%d]: %ld, e2[%d]: %ld\n", i, e1[i], i, e2[i]);
    }
  }

  if (good) {
    printf("CBD good!\n");
  }

  printf("---------- TEST AES ----------\n");

  good = true;
  uint8_t seed[SEED_BYTES];
  randombytes(seed, SEED_BYTES);

  xof((uint8_t *)e1, 8 * n, seed, SEED_BYTES);
  aes128_key_expand(seed);

  if (good) {
    printf("AES good!\n");
  }

  poly_free(&e1);
  poly_free(&e2);

  return 0;
}
