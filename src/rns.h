
#ifndef __RNS_H__
#define __RNS_H__

#include "poly.h"

typedef poly* rns;  // L polynomials (one per q_i)

/*
  @param a: rns to be allocated
  @param n: size of the ring
  @param l: size of the rns
*/
void rns_new(rns* a, uint32_t n, uint32_t l);

/*
  @param a: rns to be set free
  @param l: size of the rns
*/
void rns_free(rns* a, uint32_t l);

/*
  @param roots: input primitive roots of each moduli
  @param q: input modulus
  @param qR: input R=2^64 in the l modulis
  @param qinv: input inverse of the l q's mod 2^64
  @param n: size of the ring
  @param l: size of the rns
  @param s: output secret key
*/
void rns_gen_secret_key(rns s, const rns roots, const uint64_t* q,
                        const int64_t* qR, const int64_t* qinv, uint32_t n,
                        uint32_t l);

/*
  @param q: input modulus
  @param qR: input R=2^64 in the l modulis
  @param qinv: input inverse of the l q's mod 2^64
  @param n: size of the ring
  @param l: size of the rns
  @param roots: output primitive roots of each moduli
*/
void rns_gen_roots(rns roots, const uint64_t* q, const int64_t* qR, const int64_t* qinv,
                   uint32_t n, uint32_t l);

/*
  Supposes that roots was generated by rns_gen_roots
  @param q: input modulus
  @param qinv: input inverse of the l q's mod 2^64
  @param n: size of the ring
  @param l: size of the rns
  @param roots: input/output primitive roots of each moduli
*/
void rns_gen_inverse_roots(rns roots, const uint64_t* q, const int64_t* qinv,
                           uint32_t n, uint32_t l);

/*
  @param l: size of the rns
  @param qn: output R^2/n, R=2^64 in q modulis
  @param qR: output R=2^64 in the l modulis
  @param qinv: output inverse of the l q's mod 2^64
*/
void rns_gen_q_new(int64_t** qn, int64_t** qR, int64_t** qinv, uint32_t l);

/*
  @param q: input modulus
  @param n: size of the ring
  @param l: size of the rns
  @param qn: output R^2/n, R=2^64 in q modulis
  @param qR: output R=2^64 in the l modulis
  @param qinv: output inverse of the l q's mod 2^64
*/
void rns_gen_q_aux(int64_t* qn, int64_t* qR, int64_t* qinv, const uint64_t* q,
                   uint32_t n, uint32_t l);

/*
  @param qn: output R^2/n, R=2^64 in q modulis
  @param qR: output R=2^64 in the l modulis
  @param qinv: output inverse of the l q's mod 2^64
*/
void rns_gen_q_free(int64_t** qn, int64_t** qR, int64_t** qinv);

#endif  // __RNS_H__
