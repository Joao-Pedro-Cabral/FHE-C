
#ifndef __RNS_H__
#define __RNS_H__

#include "poly.h"

typedef poly* rns;  // L polynomials (one per q_i)

typedef struct {
  const uint64_t* q;  // l modulus
  int64_t* qinv;      // inverse of the l q's mod 2^64
  int64_t* qR;        // R=2^64 in the l modulis
  int64_t* qRq;       // R/q, round even
  int64_t* qR2n;      // R^2/n, R=2^64 in q modulis
  uint32_t l;         // size of the rms
  uint32_t n;         // size of the polynomials
  rns w;              // roots for each ring
} rns_params;

/*
  @param a: rns to be allocated
  @param params: RNS params
*/
void rns_new(rns* a, const rns_params* params);

/*
  @param a: rns to be set free
  @param params: RNS params
*/
void rns_free(rns* a, const rns_params* params);

/*
  @param params: RNS params
*/
void rns_gen_roots(rns_params* params);

/*
  Supposes that roots was generated by rns_gen_roots
  @param params: RNS params
*/
void rns_gen_inverse_roots(rns_params* params);

/*
  @param params: RNS params
*/
void rns_params_new(rns_params* params, const uint64_t* q, uint32_t n,
                    uint32_t l);

/*
  @param params: RNS params
*/
void rns_params_free(rns_params* params);

#endif  // __RNS_H__
